function migrate(data) {
  if (!Array.isArray(data.devices) || !data.devices.length) data.devices = defaultDevices();
  (data.users || []).forEach((u) => {
    if (u.role === "viewer") {
      u.role = "other";
      u.roleTitle = u.roleTitle || "مراقب ميداني";
    }
    if (u.role !== "pm") u.role = "other";
    if (u.roleTitle == null) u.roleTitle = "";
    if (!u.deviceScope) u.deviceScope = u.role === "pm" ? "all" : "all";
  });
  (data.projects || []).forEach((p) => {
    if (!p.files) p.files = [];
    if (!p.location) p.location = (p.info && p.info.location) || "";
    if (!Array.isArray(p.extra)) {
      p.extra = [];
      const skip = { name: 1, hospital: 1, location: 1, device: 1 };
      (data.infoFields || []).forEach((f) => {
        if (!f || skip[f.id] || f.core) return;
        p.extra.push({
          id: f.id,
          ar: f.ar || f.id,
          en: f.en || f.id,
          value: (p.info && p.info[f.id]) || ""
        });
      });
      Object.keys(p.info || {}).forEach((id) => {
        if (skip[id] || p.extra.some((x) => x.id === id)) return;
        p.extra.push({ id, ar: id, en: id, value: p.info[id] || "" });
      });
    }
    (p.tasks || []).forEach(function walk(task) {
      if (!task.children) task.children = [];
      if (!task.costFiles) task.costFiles = [];
      task.children.forEach(walk);
    });
    rollupProject(p);
  });
  return data;
}

function loadLocalFallback() {
  const raw = localStorage.getItem(KEY) || localStorage.getItem("med-install-pm-v1");
  if (raw) {
    try {
      return migrate(JSON.parse(raw));
    } catch (err) {
      /* ignore */
    }
  }
  const data = seed();
  return data;
}

function compactData(data) {
  const copy = JSON.parse(JSON.stringify(data || { users: [], projects: [] }));
  const slim = (files) =>
    (files || []).map((f) => ({
      id: f.id,
      name: f.name,
      type: f.type,
      size: f.size,
      driveFileId: f.driveFileId || "",
      url: f.url || ""
    }));
  (copy.projects || []).forEach((p) => {
    p.files = slim(p.files);
    (p.tasks || []).forEach(function walk(task) {
      task.costFiles = slim(task.costFiles);
      (task.children || []).forEach(walk);
    });
  });
  return copy;
}

let saveTimer = null;
let toastTimer = null;

function showToast(msg, isError) {
  let t = document.getElementById("save-toast");
  if (!t) {
    t = document.createElement("div");
    t.id = "save-toast";
    t.className = "save-toast";
    document.body.appendChild(t);
  }
  t.textContent = msg;
  t.classList.toggle("error", !!isError);
  t.classList.add("show");
  clearTimeout(toastTimer);
  toastTimer = setTimeout(() => t.classList.remove("show"), 2200);
}

